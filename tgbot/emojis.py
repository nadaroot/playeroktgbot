def tg_emoji(name: str, fallback: str = "") -> str:
    """Форматирует тег <tg-emoji> для HTML-разметки сообщения."""
    emoji_id = EMOJI_IDS.get(name)
    if emoji_id:
        return f'<tg-emoji emoji-id="{emoji_id}">{fallback}</tg-emoji>'
    return fallback


def p_btn(text: str, emoji_name: Optional[str] = None, **kwargs) -> InlineKeyboardButton:
    """Создаёт InlineKeyboardButton с icon_custom_emoji_id (без обычных эмодзи в тексте)."""
    emoji_id = EMOJI_IDS.get(emoji_name) if emoji_name else None
    if emoji_id:
        return InlineKeyboardButton(text=text, icon_custom_emoji_id=emoji_id, **kwargs)
    return InlineKeyboardButton(text=text, **kwargs)
